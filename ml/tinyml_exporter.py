"""
TinyML C++ Exporter for ISL Sensor Glove.
Converts trained Scikit-Learn Decision Tree and Random Forest models into
pure, zero-dependency, ultra-fast C++ header/source files for direct on-device
inference on the ESP32 microcontroller (< 1ms execution, no heap allocation).
"""

import os
import json
import joblib
import numpy as np
from typing import Dict, Any, List, Optional
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier


class TinyMLExporter:
    def __init__(
        self,
        models_dir: str = "models/saved",
        esp32_dir: str = "esp32"
    ):
        self.models_dir = models_dir
        self.esp32_dir = esp32_dir
        self.feature_names = [
            "thumb", "index", "middle", "ring", "little",
            "acc_x", "acc_y", "acc_z",
            "gyro_x", "gyro_y", "gyro_z"
        ]

    def _generate_tree_cpp(self, tree, classes: List[str], indent: str = "    ") -> str:
        """Recursively generate C++ if-else branches for a single decision tree."""
        left = tree.children_left
        right = tree.children_right
        threshold = tree.threshold
        features = tree.feature
        values = tree.value

        def recurse(node_id: int, current_indent: str) -> str:
            if left[node_id] == -1 and right[node_id] == -1:
                class_counts = values[node_id][0]
                total = np.sum(class_counts)
                if total > 0:
                    probs = class_counts / total
                else:
                    probs = np.zeros(len(classes))
                top_class_idx = int(np.argmax(probs))
                confidence = float(probs[top_class_idx])
                return f"{current_indent}return {{ {top_class_idx}, {confidence:.4f}f }};\n"

            feat_idx = features[node_id]
            feat_name = self.feature_names[feat_idx]
            thresh_val = threshold[node_id]

            code = f"{current_indent}if (features[{feat_idx}] <= {thresh_val:.5f}f) {{ // {feat_name}\n"
            code += recurse(left[node_id], current_indent + "    ")
            code += f"{current_indent}}} else {{\n"
            code += recurse(right[node_id], current_indent + "    ")
            code += f"{current_indent}}}\n"
            return code

        return recurse(0, indent)

    def export_decision_tree(
        self,
        model_name: str = "decision_tree",
        output_header_path: Optional[str] = None,
        output_source_path: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Export trained Decision Tree to pure C++ for ESP32.
        """
        model_file = os.path.join(self.models_dir, f"{model_name}.joblib")
        encoder_file = os.path.join(self.models_dir, "label_encoder.joblib")

        if not os.path.exists(model_file):
            model_file = os.path.join(self.models_dir, "best_model.joblib")

        if not os.path.exists(model_file) or not os.path.exists(encoder_file):
            raise FileNotFoundError(f"Model or label encoder not found at {model_file}")

        clf = joblib.load(model_file)
        encoder = joblib.load(encoder_file)
        classes = list(encoder.classes_)
        num_classes = len(classes)

        if isinstance(clf, RandomForestClassifier):
            tree = clf.estimators_[0].tree_
        elif hasattr(clf, "tree_"):
            tree = clf.tree_
        else:
            raise TypeError(f"Model {type(clf)} is not a DecisionTree or RandomForest.")

        header_path = output_header_path or os.path.join(self.esp32_dir, "TinyML_Classifier.h")
        source_path = output_source_path or os.path.join(self.esp32_dir, "TinyML_Classifier.cpp")
        os.makedirs(os.path.dirname(header_path), exist_ok=True)
        os.makedirs(os.path.dirname(source_path), exist_ok=True)

        classes_array_str = ", ".join([f'"{c}"' for c in classes])
        header_code = f"""/**
 * TinyML On-Device Classifier for ESP32
 * Autogenerated by ISL Glove TinyMLExporter
 * Features: 11 inputs (thumb, index, middle, ring, little, ax, ay, az, gx, gy, gz)
 * Output: 20 ISL Gesture Classes (< 1ms latency, 0 dynamic RAM)
 */

#ifndef TINYML_CLASSIFIER_H
#define TINYML_CLASSIFIER_H

#include <Arduino.h>

#define TINYML_NUM_FEATURES 11
#define TINYML_NUM_CLASSES  {num_classes}

struct TinyMLResult {{
    int class_id;
    float confidence;
    const char* gesture_name;
}};

class TinyMLClassifier {{
public:
    static const char* const CLASS_NAMES[TINYML_NUM_CLASSES];
    
    // Perform instant on-chip inference
    static TinyMLResult predict(const float features[TINYML_NUM_FEATURES]);
}};

#endif // TINYML_CLASSIFIER_H
"""

        tree_logic = self._generate_tree_cpp(tree, classes, indent="    ")

        source_code = f"""/**
 * TinyML On-Device Classifier Implementation for ESP32
 * Autogenerated by ISL Glove TinyMLExporter
 */

#include "TinyML_Classifier.h"

const char* const TinyMLClassifier::CLASS_NAMES[TINYML_NUM_CLASSES] = {{
    {classes_array_str}
}};

struct LeafResult {{
    int class_id;
    float confidence;
}};

static LeafResult evaluateTree(const float features[TINYML_NUM_FEATURES]) {{
{tree_logic}
}}

TinyMLResult TinyMLClassifier::predict(const float features[TINYML_NUM_FEATURES]) {{
    LeafResult res = evaluateTree(features);
    
    TinyMLResult out;
    out.class_id = res.class_id;
    out.confidence = res.confidence;
    
    if (res.class_id >= 0 && res.class_id < TINYML_NUM_CLASSES) {{
        out.gesture_name = CLASS_NAMES[res.class_id];
    }} else {{
        out.gesture_name = "UNKNOWN";
    }}
    
    return out;
}}
"""

        with open(header_path, "w", encoding="utf-8") as f:
            f.write(header_code)
        with open(source_path, "w", encoding="utf-8") as f:
            f.write(source_code)

        return {
            "header_path": header_path,
            "source_path": source_path,
            "num_classes": num_classes,
            "classes": classes
        }
